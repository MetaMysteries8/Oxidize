"""Existing return/error tests intentionally do not assert in-place mutation."""
from pathlib import Path
import unittest
from mutate import total_and_mark


class MutationTests(unittest.TestCase):
    def test_returns(self):
        # Ordinary generated output must not contaminate the canonical checkpoint.
        Path("test-output.txt").write_text("generated by independent tests")
        for values, expected in [([], 0), ([1, 2, 3], 6), ([0], 0)]:
            self.assertEqual(total_and_mark(values), expected)

    def test_error(self):
        with self.assertRaisesRegex(ValueError, "^negative total$"):
            total_and_mark([-2, 1])
